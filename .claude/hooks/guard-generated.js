#!/usr/bin/env node
// PreToolUse hook: block hand-edits to generated build artifacts.
//
// reason: src/assets/css/styles.css is committed to the repo but is *output* of
// `npm run build:css`. A hand-edit looks like it worked, survives until the next
// build, then silently disappears — and because src/_data/assetVersion.js hashes
// the file, a stray edit also churns the cache-busting token for no reason.
// The fix always belongs in input.css or in the template's utility classes.
//
// Exit code 2 blocks the tool call and feeds stderr back to the model.

const path = require("path");

const PROJECT_DIR = path.resolve(__dirname, "..", "..");

const GENERATED = [
  {
    match: /^src[\\/]assets[\\/]css[\\/]styles\.css$/i,
    why: "generated by `npm run build:css` from src/assets/css/input.css",
    instead:
      "Edit src/assets/css/input.css (for custom CSS) or the Tailwind classes in the template. The build:css hook recompiles automatically.",
  },
  {
    match: /^_site[\\/]/i,
    why: "Eleventy build output",
    instead: "Edit the source under src/ and re-run `npm run build`.",
  },
];

function readStdin() {
  try {
    return require("fs").readFileSync(0, "utf8");
  } catch {
    return "";
  }
}

function main() {
  let payload;
  try {
    payload = JSON.parse(readStdin() || "{}");
  } catch {
    return; // Can't parse: don't block.
  }

  const raw = (payload.tool_input || {}).file_path || "";
  if (!raw) return;

  const rel = path.relative(PROJECT_DIR, path.resolve(PROJECT_DIR, raw));
  if (rel.startsWith("..")) return;

  const hit = GENERATED.find((g) => g.match.test(rel));
  if (!hit) return;

  process.stderr.write(
    `Blocked: ${rel} is ${hit.why}. Hand-edits are overwritten by the next build.\n` +
      `${hit.instead}\n`
  );
  process.exit(2);
}

main();
